import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Precache exactly this production build. No data endpoints, runtime libraries,
// background sync, or external resources are involved.
const root = new URL('../dist/', import.meta.url);
const names = (await readdir(root, { recursive: true, withFileTypes: true }))
  .filter((entry) => entry.isFile())
  .map((entry) => relative(fileURLToPath(root), resolve(entry.parentPath, entry.name)).replaceAll('\\', '/'))
  .filter((name) => name !== 'sw.js').sort();
const hash = createHash('sha256');
for (const name of names) hash.update(name).update(await readFile(new URL(name, root)));
const cache = `zymptom-m0-shell-${hash.digest('hex').slice(0, 16)}`;
await writeFile(new URL('sw.js', root), `/* Generated by build-sw.mjs; shell only. */
const CACHE = ${JSON.stringify(cache)};
const SHELL = ${JSON.stringify(names.map((name) => `/${name}`))};
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(SHELL)));
});
self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) {
      if (key.startsWith('zymptom-m0-shell-') && key !== CACHE) await caches.delete(key);
    }
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (event.request.mode === 'navigate') {
    event.respondWith(caches.open(CACHE).then((cache) => cache.match('/index.html')));
  } else if (SHELL.includes(url.pathname) && !url.search) {
    event.respondWith(caches.open(CACHE).then((cache) => cache.match(url.pathname)));
  }
});
`);
console.log(`Offline shell: ${names.length} files, ${cache}`);

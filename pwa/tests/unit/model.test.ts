import { describe, expect, it } from 'vitest';
import fixture from '../fixtures/z5-v1.json';
import { addSelected, contract, localDate, localInput, occurredFromInput, tagFields, unique, utc, validateEpisode } from '../../src/model';

describe('desktop v1 compatibility', () => {
  it('accepts complete snapshots generated by Python Z5, including exact microseconds and stable machine values', () => {
    expect(fixture.contract_version).toBe(contract.contract_version);
    expect(fixture.record_schema_version).toBe(contract.record_schema_version);
    const [create, deleted] = fixture.changes;
    validateEpisode(create.episode);
    expect(create.record_type).toBe(contract.record_type);
    expect(create.record_id).toBe(create.episode!.id);
    expect(create.episode!.outcome).toBe('completed_with_difficulty');
    expect(create.episode!.help_level).toBe('none');
    expect(create.episode!.resume_ability).toBe('after_short_break');
    expect(create.episode!.duration_minutes).toBe(0);
    expect(create.episode!.recovery_required).toBe(false);
    expect(create.episode!.recovery_minutes).toBeNull();
    expect(create.episode!.help_notes).toBe('');
    expect(create.episode!.symptom_notes).toBe('雪\nSecond line');
    expect(utc(create.episode!.occurred_at)).toBe('2026-10-25T22:15:30.123456+00:00');
    expect(deleted.deleted).toBe(true);
    expect(deleted.episode).toBeNull();
    expect(deleted.parent_ids).toEqual([create.change_id]);
    for (const field of tagFields) {
      for (const value of create.episode![field]) expect(contract.tags[field]).toHaveProperty(value);
    }
  });

  it('preserves UTC precision and normalizes offsets without losing microseconds', () => {
    expect(utc('2026-10-25T23:30:12.987654-07:00')).toBe('2026-10-26T06:30:12.987654+00:00');
    expect(utc('2026-01-01T00:00:00Z')).toBe('2026-01-01T00:00:00.000000+00:00');
    const original = fixture.changes[0].episode!.occurred_at;
    expect(occurredFromInput(localInput(original), original)).toBe(original);
  });

  it.each(['2026-01-01T00:00:00', '2026-02-30T00:00:00Z', '2026-01-01T24:00:00Z', 'not a date'])('rejects invalid/naive timestamp %s', (value) => {
    expect(() => utc(value)).toThrow();
  });

  it('refuses invented enums, invalid lists and missing fields', () => {
    const episode = structuredClone(fixture.changes[0].episode!);
    expect(() => validateEpisode({ ...episode, outcome: 'felt_ok' })).toThrow();
    expect(() => validateEpisode({ ...episode, symptoms: [123] })).toThrow();
    expect(() => validateEpisode({ ...episode, recovery_required: 0 })).toThrow();
    const { notes: _, ...missing } = episode;
    expect(() => validateEpisode(missing)).toThrow();
  });

  it('preserves a DST fold and rejects nonexistent local wall times without moving the local date', () => {
    const previous = process.env.TZ;
    process.env.TZ = 'America/Los_Angeles';
    try {
      const fold = '2026-11-01T09:30:00.123456+00:00';
      expect(localInput(fold)).toBe('2026-11-01T01:30');
      expect(occurredFromInput('2026-11-01T01:30', fold)).toBe(fold);
      expect(() => occurredFromInput('2026-03-08T02:30', fold)).toThrow('valid local date');
      expect(localDate('2026-10-26T06:59:00.000000+00:00')).toBe('2026-10-25');
      expect(localDate('2026-10-26T07:00:00.000000+00:00')).toBe('2026-10-26');
    } finally {
      if (previous === undefined) delete process.env.TZ;
      else process.env.TZ = previous;
    }
  });
});

it('adds all selections in click order, skips duplicates, and supports removal/re-add', () => {
  const original = ['walking', 'memory'];
  expect(addSelected(original, ['memory', 'sitting', 'pain', 'sitting'])).toEqual(['walking', 'memory', 'sitting', 'pain']);
  expect(original).toEqual(['walking', 'memory']);
  expect(addSelected(['memory'], ['walking'])).toEqual(['memory', 'walking']);
  expect(unique(['pain', 'fatigue', 'pain'])).toEqual(['pain', 'fatigue']);
});
